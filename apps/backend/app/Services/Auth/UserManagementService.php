<?php

namespace App\Services\Auth;

use App\Enums\RoleStatus;
use App\Enums\UserStatus;
use App\Exceptions\ApiException;
use App\Models\User;
use Illuminate\Support\Facades\DB;

/**
 * Administrative user management (AUTH-010).
 *
 * Owns account lifecycle logic (create, update, status change, admin password
 * reset) so controllers stay thin. Reuses PasswordService (AUTH-006),
 * AccountSecurityService (AUTH-006), and SessionRevocationService. Emits no
 * audit records (AUTH-014) but exposes discrete methods that later audit
 * listeners can hook: USER_CREATED / USER_UPDATED / USER_ENABLED /
 * USER_DISABLED / PASSWORD_RESET.
 *
 * Authorization is enforced by permission middleware, never by role name. The
 * SUPER_ADMIN role code is referenced ONLY for the last-admin protection
 * invariant (a system-protection rule, not an authorization bypass).
 */
class UserManagementService
{
    private const SUPER_ADMIN_CODE = 'SUPER_ADMIN';

    public function __construct(
        private readonly PasswordService $passwords,
        private readonly AccountSecurityService $accountSecurity,
        private readonly SessionRevocationService $sessions,
    ) {}

    /**
     * Create a user account. Password is validated against policy and stored
     * hashed; the UUID is generated server-side; person_id stays null.
     *
     * @param  array{username:string, email?:?string, password:string, status?:string, must_change_password?:bool}  $data
     */
    public function create(array $data): User
    {
        $this->passwords->validatePassword($data['password']);

        return DB::transaction(function () use ($data) {
            $user = new User;
            $user->username = $data['username'];
            $user->email = $data['email'] ?? null;
            $user->status = UserStatus::from($data['status'] ?? UserStatus::ACTIVE->value);
            $user->must_change_password = (bool) ($data['must_change_password'] ?? false);
            $user->password = $data['password']; // hashed via cast
            $user->password_changed_at = now();
            $user->save(); // uuid auto-generated by HasPublicUuid

            return $user;
        });
    }

    /**
     * Update whitelisted account identity fields only (username, email).
     * Security-state and credential fields are never touched here.
     *
     * @param  array{username?:string, email?:?string}  $data
     */
    public function update(User $user, array $data): User
    {
        return DB::transaction(function () use ($user, $data) {
            if (array_key_exists('username', $data)) {
                $user->username = $data['username'];
            }
            if (array_key_exists('email', $data)) {
                $user->email = $data['email'];
            }
            $user->save();

            return $user;
        });
    }

    /**
     * Change a user's account status with lifecycle side effects.
     *
     * Guards self-disable/lock/expire and last-SUPER_ADMIN removal, applies the
     * correct persistent-status semantics (LOCKED via status, never
     * locked_until), and revokes active sessions when the account becomes
     * non-ACTIVE. Concurrency-safe via row locks inside the transaction.
     */
    public function changeStatus(User $target, UserStatus $newStatus, User $actor): User
    {
        $makesUnusable = $newStatus !== UserStatus::ACTIVE;

        // Self-disable/lock/expire protection (backend rule, not just UI).
        if ($makesUnusable && $actor->id === $target->id) {
            throw ApiException::conflict(
                'USER_SELF_DISABLE_FORBIDDEN',
                'You cannot disable, lock, or expire your own account.'
            );
        }

        return DB::transaction(function () use ($target, $newStatus, $makesUnusable) {
            $fresh = User::whereKey($target->id)->lockForUpdate()->firstOrFail();

            if ($makesUnusable) {
                $this->assertNotLastUsableSuperAdmin($fresh);
            }

            switch ($newStatus) {
                case UserStatus::ACTIVE:
                    if ($fresh->status === UserStatus::LOCKED) {
                        $this->accountSecurity->unlockUser($fresh);
                    } else {
                        $fresh->status = UserStatus::ACTIVE;
                        $fresh->save();
                    }
                    break;

                case UserStatus::LOCKED:
                    // Persistent administrative lock (status only, not locked_until).
                    $this->accountSecurity->lockUser($fresh);
                    break;

                case UserStatus::DISABLED:
                case UserStatus::EXPIRED:
                    $fresh->status = $newStatus;
                    $fresh->save();
                    break;
            }

            if ($makesUnusable) {
                $this->sessions->revokeAllForUser($fresh);
            }

            $target->status = $fresh->status;

            return $fresh;
        });
    }

    /**
     * Administrative password reset: validate policy, store hashed, force a
     * change on next login, and revoke active sessions. Never returns or logs
     * the plaintext password.
     */
    public function resetPassword(User $target, string $newPassword): User
    {
        return DB::transaction(function () use ($target, $newPassword) {
            $updated = $this->passwords->updatePassword($target, $newPassword, mustChangePassword: true);
            $this->sessions->revokeAllForUser($updated);

            return $updated;
        });
    }

    /**
     * Reject an operation that would remove the last usable SUPER_ADMIN.
     *
     * "Usable" = ACTIVE, not temporarily locked, holding a currently-valid
     * assignment to the ACTIVE SUPER_ADMIN role. Row-locks the usable-admin set
     * so two concurrent transactions cannot both disable the last two admins.
     */
    private function assertNotLastUsableSuperAdmin(User $target): void
    {
        $now = now();

        $usableSuperAdminIds = DB::table('users')
            ->join('user_roles', 'users.id', '=', 'user_roles.user_id')
            ->join('roles', 'user_roles.role_id', '=', 'roles.id')
            ->where('roles.code', self::SUPER_ADMIN_CODE)
            ->where('roles.status', RoleStatus::ACTIVE->value)
            ->where('users.status', UserStatus::ACTIVE->value)
            ->whereNull('users.deleted_at')
            ->where(function ($q) use ($now) {
                $q->whereNull('users.locked_until')->orWhere('users.locked_until', '<=', $now);
            })
            ->where(function ($q) use ($now) {
                $q->whereNull('user_roles.valid_from')->orWhere('user_roles.valid_from', '<=', $now);
            })
            ->where(function ($q) use ($now) {
                $q->whereNull('user_roles.valid_until')->orWhere('user_roles.valid_until', '>=', $now);
            })
            ->lockForUpdate()
            ->pluck('users.id')
            ->unique();

        if (! $usableSuperAdminIds->contains($target->id)) {
            return; // target is not a usable super admin — nothing to protect
        }

        $remaining = $usableSuperAdminIds->reject(fn ($id) => (int) $id === (int) $target->id);

        if ($remaining->isEmpty()) {
            throw ApiException::conflict(
                'LAST_SUPER_ADMIN_REQUIRED',
                'This is the last usable SUPER_ADMIN account and cannot be disabled, locked, or expired.'
            );
        }
    }
}
