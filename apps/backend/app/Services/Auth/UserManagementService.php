<?php

namespace App\Services\Auth;

use App\Enums\AuditAction;
use App\Enums\RoleStatus;
use App\Enums\UserStatus;
use App\Exceptions\ApiException;
use App\Models\User;
use App\Services\Audit\AuditRequestContext;
use App\Services\Audit\AuditService;
use Illuminate\Support\Facades\DB;

/**
 * Administrative user management (AUTH-010, AUTH-014).
 *
 * Owns account lifecycle logic (create, update, status change, admin password
 * reset) with transactional audit logging (AUTH-014).
 */
class UserManagementService
{
    private const SUPER_ADMIN_CODE = 'SUPER_ADMIN';

    public function __construct(
        private readonly PasswordService $passwords,
        private readonly AccountSecurityService $accountSecurity,
        private readonly SessionRevocationService $sessions,
        private readonly AuditService $auditService,
    ) {}

    /**
     * Create a user account.
     *
     * @param  array{username:string, email?:?string, password:string, status?:string, must_change_password?:bool}  $data
     */
    public function create(array $data, ?User $actor = null, ?AuditRequestContext $context = null): User
    {
        $this->passwords->validatePassword($data['password']);

        return DB::transaction(function () use ($data, $actor, $context) {
            $user = new User;
            $user->username = $data['username'];
            $user->email = $data['email'] ?? null;
            $user->status = UserStatus::from($data['status'] ?? UserStatus::ACTIVE->value);
            $user->must_change_password = (bool) ($data['must_change_password'] ?? false);
            $user->password = $data['password']; // hashed via cast
            $user->password_changed_at = now();
            $user->save(); // uuid auto-generated by HasPublicUuid

            $this->auditService->record(
                AuditAction::USER_CREATED,
                $actor,
                'USER',
                $user->uuid,
                newValues: [
                    'username' => $user->username,
                    'email' => $user->email,
                    'status' => $user->status->value,
                    'must_change_password' => $user->must_change_password,
                ],
                context: $context
            );

            return $user;
        });
    }

    /**
     * Update whitelisted account identity fields only (username, email).
     *
     * @param  array{username?:string, email?:?string}  $data
     */
    public function update(User $user, array $data, ?User $actor = null, ?AuditRequestContext $context = null): User
    {
        return DB::transaction(function () use ($user, $data, $actor, $context) {
            $oldValues = [];
            $newValues = [];

            if (array_key_exists('username', $data) && $data['username'] !== $user->username) {
                $oldValues['username'] = $user->username;
                $newValues['username'] = $data['username'];
                $user->username = $data['username'];
            }

            if (array_key_exists('email', $data) && $data['email'] !== $user->email) {
                $oldValues['email'] = $user->email;
                $newValues['email'] = $data['email'];
                $user->email = $data['email'];
            }

            if (! empty($newValues)) {
                $user->save();

                $this->auditService->record(
                    AuditAction::USER_UPDATED,
                    $actor,
                    'USER',
                    $user->uuid,
                    oldValues: $oldValues,
                    newValues: $newValues,
                    context: $context
                );
            }

            return $user;
        });
    }

    /**
     * Change a user's account status with lifecycle side effects.
     */
    public function changeStatus(User $target, UserStatus $newStatus, User $actor, ?AuditRequestContext $context = null): User
    {
        $makesUnusable = $newStatus !== UserStatus::ACTIVE;

        // Self-disable/lock/expire protection
        if ($makesUnusable && $actor->id === $target->id) {
            throw ApiException::conflict(
                'USER_SELF_DISABLE_FORBIDDEN',
                'You cannot disable, lock, or expire your own account.'
            );
        }

        return DB::transaction(function () use ($target, $newStatus, $actor, $context, $makesUnusable) {
            $fresh = User::whereKey($target->id)->lockForUpdate()->firstOrFail();

            if ($makesUnusable) {
                $this->assertNotLastUsableSuperAdmin($fresh);
            }

            $oldStatus = $fresh->status;

            switch ($newStatus) {
                case UserStatus::ACTIVE:
                    if ($fresh->status === UserStatus::LOCKED) {
                        $this->accountSecurity->unlockUser($fresh);
                    } else {
                        $fresh->status = UserStatus::ACTIVE;
                        $fresh->save();
                    }
                    break;

                case UserStatus::LOCKED:
                    $this->accountSecurity->lockUser($fresh);
                    break;

                case UserStatus::DISABLED:
                case UserStatus::EXPIRED:
                    $fresh->status = $newStatus;
                    $fresh->save();
                    break;
            }

            $revokedCount = 0;
            if ($makesUnusable) {
                $revokedCount = $this->sessions->revokeAllForUser($fresh);
            }

            $target->status = $fresh->status;

            $this->auditService->record(
                AuditAction::USER_STATUS_CHANGED,
                $actor,
                'USER',
                $fresh->uuid,
                oldValues: ['status' => $oldStatus->value],
                newValues: [
                    'status' => $fresh->status->value,
                    'revoked_sessions_count' => $revokedCount,
                ],
                context: $context
            );

            return $fresh;
        });
    }

    /**
     * Administrative password reset.
     */
    public function resetPassword(User $target, string $newPassword, ?User $actor = null, ?AuditRequestContext $context = null): User
    {
        return DB::transaction(function () use ($target, $newPassword, $actor, $context) {
            $updated = $this->passwords->updatePassword($target, $newPassword, mustChangePassword: true);
            $revokedCount = $this->sessions->revokeAllForUser($updated);

            $this->auditService->record(
                AuditAction::USER_PASSWORD_RESET,
                $actor,
                'USER',
                $updated->uuid,
                newValues: [
                    'must_change_password' => true,
                    'revoked_sessions_count' => $revokedCount,
                ],
                context: $context
            );

            return $updated;
        });
    }

    /**
     * Reject an operation that would remove the last usable SUPER_ADMIN.
     */
    private function assertNotLastUsableSuperAdmin(User $target): void
    {
        $now = now();

        $usableSuperAdminIds = DB::table('users')
            ->join('user_roles', 'users.id', '=', 'user_roles.user_id')
            ->join('roles', 'user_roles.role_id', '=', 'roles.id')
            ->where('roles.code', self::SUPER_ADMIN_CODE)
            ->where('roles.status', RoleStatus::ACTIVE->value)
            ->where('users.status', UserStatus::ACTIVE->value)
            ->whereNull('users.deleted_at')
            ->where(function ($q) use ($now) {
                $q->whereNull('users.locked_until')->orWhere('users.locked_until', '<=', $now);
            })
            ->where(function ($q) use ($now) {
                $q->whereNull('user_roles.valid_from')->orWhere('user_roles.valid_from', '<=', $now);
            })
            ->where(function ($q) use ($now) {
                $q->whereNull('user_roles.valid_until')->orWhere('user_roles.valid_until', '>=', $now);
            })
            ->lockForUpdate()
            ->pluck('users.id')
            ->all();

        if (in_array($target->id, $usableSuperAdminIds, true) && count($usableSuperAdminIds) <= 1) {
            throw ApiException::conflict(
                'LAST_SUPER_ADMIN_REQUIRED',
                'Cannot modify status: this is the last usable SUPER_ADMIN.'
            );
        }
    }
}
